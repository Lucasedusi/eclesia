import { test, expect } from "@playwright/test";
import { readFileSync } from "node:fs";
const fixture = () => JSON.parse(readFileSync(process.env.E2E_FINANCE_FIXTURE!, "utf8"));
test.beforeEach(() => test.skip(!process.env.E2E_FINANCE_FIXTURE, "Local fixture required"));

test("automatic cents support real keystrokes, editing, clearing and formatted paste", async ({ page, context }) => {
  const f = fixture();
  await page.goto(`/financeiro/atendimento?unidade=${f.unitId}&mes=2026-10`);
  const money = page.getByRole("textbox", { name: "Valor (R$)", exact: true });
  await money.pressSequentially("1234");
  await expect(money).toHaveValue("12,34");
  await expect(page.getByTestId("attendance-total")).toContainText("12,34");
  await money.press("Backspace");
  await expect(money).toHaveValue("1,23");
  await money.evaluate((el: HTMLInputElement) => el.setSelectionRange(2, 2));
  await money.press("Backspace");
  await expect(money).toHaveValue("0,23");
  await money.fill("");
  await expect(money).toHaveValue("");
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await page.evaluate(() => navigator.clipboard.writeText("R$ 1.234,50"));
  await money.focus();
  await money.press("ControlOrMeta+V");
  await expect(money).toHaveValue("1.234,50");
  await money.blur();
  await expect(money).toHaveValue("1.234,50");
  const buttons = page.locator(".finance-attendance-action");
  const icons = await buttons.locator(".finance-action-icon").evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().x));
  expect(new Set(icons).size).toBe(1);
  await page.screenshot({ path: "tmp/finance-final-attendance.png", fullPage: true });
});

test("search can be cleared and advanced reset stays inside expanded filters", async ({ page }) => {
  const f = fixture();
  await page.goto(`/financeiro/lancamentos?unidade=${f.headquartersId}&mes=2026-10`);
  await expect(page.getByRole("button", { name: "Limpar filtros", exact: true })).toHaveCount(0);
  const search = page.getByRole("textbox", { name: "Buscar", exact: true });
  await search.fill("Busca inexistente teste");
  await page.getByRole("button", { name: "Filtrar", exact: true }).click();
  await expect(page.locator(".empty")).toContainText("Nenhum lançamento encontrado");
  await expect(page.locator(".empty > svg")).toBeVisible();
  await page.getByRole("button", { name: "Limpar busca" }).click();
  await expect(search).toHaveValue("");
  await expect(page).not.toHaveURL(/search=/);
  await page.getByRole("button", { name: "Filtros avançados", exact: true }).click();
  await expect(page.getByRole("button", { name: "Limpar filtros", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Filtros avançados", exact: true }).click();
  await expect(page.getByRole("button", { name: "Limpar filtros", exact: true })).toHaveCount(0);
  const rows = page.locator(".finance-row-income,.finance-row-expense");
  await expect(rows.first()).toBeVisible();
  const row = rows.first();
  await expect(row).toHaveCSS("background-color", "rgb(255, 255, 255)");
  await expect(row.locator("td").first()).not.toHaveCSS("box-shadow", "none");
  await page.screenshot({ path: "tmp/finance-final-transactions.png", fullPage: true });
});

test("overview and report controls are compact and adapt to mobile", async ({ page }) => {
  const f = fixture();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`/financeiro?unidade=${f.unitId}&mes=2040-01`);
  await expect(page.getByRole("link", { name: "Nova entrada" })).toHaveCount(0);
  await expect(page.locator(".finance-logo b")).toHaveCSS("font-weight", "600");
  await expect(page.getByRole("heading", { name: "Visão geral", exact: true })).toBeVisible();
  await expect(page.locator(".finance-sidebar")).toBeVisible();
  const sidebar = (await page.locator(".finance-sidebar").boundingBox())!;
  const toggle = (await page.getByRole("button", { name: "Recolher menu" }).boundingBox())!;
  expect(Math.abs(toggle.x - sidebar.x - sidebar.width)).toBeLessThan(2);
  await expect(page.locator(".empty > svg").last()).toBeVisible();
  await page.goto(`/financeiro/relatorios?unidade=${f.unitId}&mes=2026-10`);
  const controls = page.locator(".finance-report-controls");
  const area = (await controls.boundingBox())!;
  const button = (await controls.getByRole("button").boundingBox())!;
  expect(Math.abs(area.x + area.width - button.x - button.width)).toBeLessThan(2);
  const select = (await controls.getByRole("combobox").boundingBox())!;
  expect(Math.abs(select.y - button.y)).toBeLessThan(2);
  expect(Math.abs(select.y + select.height - button.y - button.height)).toBeLessThan(2);
  await page.screenshot({ path: "tmp/finance-final-reports.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  const mobileArea = (await controls.boundingBox())!;
  expect((await controls.getByRole("button").boundingBox())!.width).toBeCloseTo(mobileArea.width, 0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
});
